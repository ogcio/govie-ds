import _ from 'lodash';
import type { BreakpointKey, ResponsiveValue, SpacingScale } from './constants';
import { resolveResponsive } from './utilities';
export default function classes(options: {
  container?: boolean;
  columns?: ResponsiveValue<SpacingScale>;
  gap?: ResponsiveValue<SpacingScale>;
  size?: ResponsiveValue<SpacingScale>;
  className?: string;
}): string {
  const isItem = !options.container || !_.isNil(options.size);
  return _.compact([
    options.container && 'gi-grid-container',
    options.container && getGridClasses(options.columns ?? DEFAULT_COLUMNS, 'gi-grid-columns'),
    options.container && getGridClasses(options.gap, 'gi-grid-gap'),
    isItem && 'gi-grid-item',
    isItem && getGridClasses(options.size, 'gi-grid-span'),
    options.className,
  ]).join(' ');
}
const DEFAULT_COLUMNS: Partial<Record<BreakpointKey, SpacingScale>> = {
  base: 4,
  sm: 6,
  md: 8,
  lg: 12,
};
const getGridClasses = (value: ResponsiveValue<SpacingScale> | undefined, prefix: string): string =>
  resolveResponsive(value, (v, bp) => `${bp}${prefix}-${_.clamp(v as number, 0, 12)}`);
