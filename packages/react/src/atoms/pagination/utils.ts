import clamp from 'lodash/clamp';
type PaginationListProps = {
  current: number;
  total: number;
  size?: number;
};
const MIN_SIZE = 5;

/**
 * Pages to render. Positive numbers are page links and `-1` is an ellipsis.
 * The list length is `min(size, total)` on every page, and absolute minimum `size` is 5. If not present, `size` defaults to 7.
 */
export const getPaginationList = ({ current, total, size = 7 }: PaginationListProps): number[] => {
  const length = Math.max(Math.floor(size), MIN_SIZE);
  if (total <= length) {
    return pageRange(1, total);
  }
  const pages = length - 2;
  const start = clamp(current - Math.floor(pages / 2), 2, total - pages);
  const end = start + pages - 1;
  return [1, start > 2 ? -1 : start, ...pageRange(start + 1, end - 1), end < total - 1 ? -1 : end, total];
};
const pageRange = (start: number, end: number): number[] =>
  Array.from(
    {
      length: end - start + 1,
    },
    (_, index) => start + index,
  );
